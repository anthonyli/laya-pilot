import test from 'node:test';
import assert from 'node:assert/strict';
import { HEALTH_EXPECTATIONS } from '../scripts/lib/diagnostics.mjs';
import { lines, expectation } from '../scripts/lib/language.mjs';
import {
    generateRecordedCases,
    restoreNavigationDestinations,
    assessNavigationHealth,
} from '../scripts/lib/recording-cases.mjs';

const origin = 'https://navigation.example.test';
const start = origin + '/dashboard';
const end = origin + '/indicators?tab=edit';
const pending = '业务结果待补充（录制时未设置预期）';
const urlCheck = `已到达录制页面「${end}」`;
const areaCheck = '已选中录制区域「Edit Area」';
const legacy = {
    id: 'REC-001',
    steps: `1. 打开网址 ${start}\n2. 展开「Tools」导航菜单\n3. 点击「Indicators」链接\n4. 切换到「Edit Area」区域`,
    data: JSON.stringify({ recordedScene: { kind: 'navigate', account: 'tester' } }),
    expected: [...Object.values(HEALTH_EXPECTATIONS), pending].join('\n'),
};
const next = {
    id: 'REC-002',
    steps: '点击「Add」按钮',
    data: JSON.stringify({
        recordedScene: { kind: 'create', previous: 'REC-001', account: 'tester', url: end },
    }),
};

test('new recordings derive target URL and final selected area only from pure navigation', () => {
    const click = (role, name, from, to) => ({
        kind: 'click',
        target: { role, name },
        before: { url: from },
        after: { url: to },
    });
    const actions = [
        click('link', 'Indicators', start, origin + '/indicators'),
        click('tab', 'Edit Area', origin + '/indicators', end),
    ];
    const generate = (actions) => generateRecordedCases({ url: start, actions }).cases[0];
    const entry = generate(actions);
    assert.deepEqual(
        lines(entry.expected).filter((text) => expectation(text).kind.startsWith('navigation-')),
        [urlCheck, areaCheck],
    );
    assert.ok(!entry.expected.includes(pending));
    const checkpoint = generate([
        ...actions,
        { kind: 'assert', assertion: 'visible', target: { role: 'heading', name: 'Area ready' } },
    ]);
    assert.ok(checkpoint.expected.includes('录制设置的步骤预期全部满足'));
    assert.ok(!checkpoint.expected.includes(areaCheck));
    assert.ok(generate([click('link', 'Indicators', start, start)]).expected.includes(pending));
    assert.ok(generate([click('link', 'Delete', start, end)]).expected.includes(pending));
    assert.ok(
        generate([...actions, { kind: 'unsupported', reason: 'unknown' }]).expected.includes(
            pending,
        ),
    );
    assert.ok(
        generate([
            click('link', 'Indicators', start, 'https://other.example.test/x'),
        ]).expected.includes(pending),
    );
});

test('old workbooks keep explicit assertions and only use a matching dependent entry as the landing page', () => {
    const input = { ...legacy, expected: legacy.expected + '\n页面显示「Customer count」' };
    const [upgraded] = restoreNavigationDestinations([input, next], origin);
    assert.ok(!upgraded.expected.includes(pending));
    assert.deepEqual(lines(upgraded.expected).slice(-3), [
        '页面显示「Customer count」',
        urlCheck,
        areaCheck,
    ]);
    assert.deepEqual(JSON.parse(upgraded.data).recordedScene.destination, {
        url: end,
        area: 'Edit Area',
        automaticApi: HEALTH_EXPECTATIONS.api,
    });
    const [alone] = restoreNavigationDestinations([input], origin);
    assert.ok(alone.expected.includes(areaCheck));
    assert.ok(!alone.expected.includes(urlCheck));
    for (const different of [
        { recordedScene: { kind: 'create', previous: 'unrelated', account: 'tester', url: end } },
        { recordedScene: { kind: 'create', previous: legacy.id, account: 'other', url: end } },
        {
            recordedScene: {
                kind: 'create',
                previous: legacy.id,
                account: 'tester',
                url: 'https://other.example.test/x',
            },
        },
    ]) {
        const [entry] = restoreNavigationDestinations(
            [input, { ...next, data: JSON.stringify(different) }],
            origin,
        );
        assert.deepEqual(JSON.parse(entry.data).recordedScene.destination, {
            area: 'Edit Area',
            automaticApi: HEALTH_EXPECTATIONS.api,
        });
    }
    assert.deepEqual(
        restoreNavigationDestinations(
            [{ ...legacy, steps: legacy.steps + '\n5. 点击「保存」按钮' }, next],
            origin,
        )[0].expected,
        legacy.expected,
    );
});

test('only autogenerated read diagnostics become informational, and a failed explicit assertion still gates the case', () => {
    const [entry] = restoreNavigationDestinations([legacy, next], origin);
    const api = {
        text: HEALTH_EXPECTATIONS.api,
        kind: 'api',
        status: '失败',
        reason: '400001 No data',
    };
    const result = () => ({
        status: '失败',
        stepsCompleted: true,
        health_checks: [{ ...api }],
        network_errors: [],
        assertions: [
            { kind: 'navigation-url', text: urlCheck, status: '通过' },
            { kind: 'navigation-area', text: areaCheck, status: '通过' },
            { ...api },
        ],
        browser_events: [
            { kind: 'api-body', method: 'GET', status: 200, detail: '400001 No data' },
        ],
    });
    const withExplicit = result();
    withExplicit.assertions.push({ text: '页面显示「badge」', status: '失败', reason: '缺失' });
    assessNavigationHealth(entry, withExplicit);
    assert.equal(withExplicit.status, '失败');
    assert.equal(withExplicit.browser_events[0].severity, 'info');
    assert.match(withExplicit.reason, /badge/);
    for (const patch of [
        { method: 'POST' },
        { kind: 'http', status: 503 },
        { detail: '403001：权限不足' },
        { detail: 'Session expired' },
    ]) {
        const failed = result();
        Object.assign(failed.browser_events[0], patch);
        assessNavigationHealth(entry, failed);
        assert.equal(failed.status, '失败');
        assert.equal(failed.browser_events[0].severity, undefined);
    }
    const silent = result();
    assessNavigationHealth({ ...entry, data: next.data }, silent);
    assert.equal(silent.status, '失败');
    assert.equal(silent.browser_events[0].severity, undefined);
});
